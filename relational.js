console.log(a >= b); // true
console.log(a < b); // false
console.log(a <= b); // true
console.log(a == b); // true (only chekc value)
console.log(a != b); // false (only check value)
console.log(a === b); //  (value + datatype)
console.log(a !== b); //  (value + datatype)


