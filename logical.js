// logical AND (&&) OR (||)

// AND  (must be true)
// true && true = true
// true && false = false
// false && true = false
// false && false = false

// OR (any condition will be true)
// true || true = true
// true || false = true
// false || true = true
// false || false = false


let a = 10;
let b = 20;
let c = 15;

console.log(a < b || b < c);
// true && false


console.log("vaibhav" || "sanjay");
// false && true

// Bitwise operator
// & , |. (1 = true , 0 false)

let i = 10;  // 1010
let j = 12;  // 1100
//              1110

console.log(i | j) // 8

